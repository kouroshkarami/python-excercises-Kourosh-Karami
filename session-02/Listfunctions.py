#List of numbers:
    
    
numbers = [3,5,8,2,4]
print(numbers) 

#List function 1 "append"adds a number at the end:
    
    
numbers.append(7) 
print(numbers) 


#List function 2 "insert" adds a number  in a specific index:

    

numbers.insert(3, 2)
print(numbers)


#List function 3 "remove" removes a specific number:
    
    
numbers.remove(8)
print(numbers)



#List function 4 "reverse" reverses the order of the numbers:
    
    
    
numbers.reverse()
print(numbers) 



#List function 5 "sort" sorts out the list of numbers:
    
    
    
    
numbers.sort()
print(numbers)



#List function 6 "clear" clears all numbers:
    
    
numbers.clear()
print(numbers) 










